CREATE TABLE IF NOT EXISTS unified_metadata (
    canonical_accession      TEXT PRIMARY KEY,
    source                   TEXT NOT NULL,
    title                    TEXT,
    description              TEXT,
    aliases                  TEXT CHECK (aliases IS NULL OR json_valid(aliases)),
    organism_counts          TEXT CHECK (organism_counts IS NULL OR json_valid(organism_counts)),
    common_name_counts       TEXT CHECK (common_name_counts IS NULL OR json_valid(common_name_counts)),
    dominant_scientific_name TEXT,
    dominant_common_name     TEXT,
    library_strategy_counts  TEXT CHECK (library_strategy_counts IS NULL OR json_valid(library_strategy_counts)),
    assay_l1_counts          TEXT CHECK (assay_l1_counts IS NULL OR json_valid(assay_l1_counts)),
    assay_l2_counts          TEXT CHECK (assay_l2_counts IS NULL OR json_valid(assay_l2_counts)),
    dominant_assay_l1        TEXT,
    dominant_assay_l2        TEXT,
    n_experiments            INTEGER,
    n_samples                INTEGER,
    center_name              TEXT,
    center_names             TEXT CHECK (center_names IS NULL OR json_valid(center_names)),
    pmid                     TEXT,
    journal                  TEXT,
    citation_count           INTEGER,
    first_published          DATE,
    place_name               TEXT,
    place_type               TEXT,
    short_label              TEXT,
    address_type             TEXT,
    osm_id                   TEXT,
    osm_type                 TEXT,
    place_id                 TEXT,
    longitude                REAL,
    latitude                 REAL,
    city                     TEXT,
    district                 TEXT,
    subdistrict              TEXT,
    county                   TEXT,
    suburb                   TEXT,
    neighbourhood            TEXT,
    state                    TEXT,
    state_district           TEXT,
    territory                TEXT,
    metro_area               TEXT,
    postcode                 TEXT,
    country_code             TEXT,
    country                  TEXT,
    country_mismatch         TEXT,
    geocode_score            TEXT,
    is_single_cell           INTEGER DEFAULT 0,
    single_cell_modality     TEXT,
    single_cell_counts       TEXT DEFAULT '{}',
    single_cell_file_format  TEXT
);

CREATE TABLE IF NOT EXISTS unified_centers (
    canonical_accession TEXT NOT NULL,
    center_name         TEXT NOT NULL,
    position            INTEGER NOT NULL DEFAULT 0,
    place_name          TEXT,
    place_type          TEXT,
    short_label         TEXT,
    address_type        TEXT,
    osm_id              TEXT,
    osm_type            TEXT,
    place_id            TEXT,
    longitude           REAL,
    latitude            REAL,
    city                TEXT,
    district            TEXT,
    subdistrict         TEXT,
    county              TEXT,
    suburb              TEXT,
    neighbourhood       TEXT,
    state               TEXT,
    state_district      TEXT,
    territory           TEXT,
    metro_area          TEXT,
    postcode            TEXT,
    country_code        TEXT,
    country             TEXT,
    country_mismatch    TEXT,
    geocode_score       TEXT,
    source              TEXT,
    error               TEXT,
    PRIMARY KEY (canonical_accession, center_name)
);
