-- Postgres DDL for the embedding-only ("fast") enrichment tier.
--
-- Mirrors the sql/tables/enrichment.sql _fast twins column-for-column, but as
-- its own tables rather than a version suffix like enriched_samples_v5: any
-- row here came from `enrich batch --embedding-only` (no LLM), never the
-- versioned LLM pipeline, and cell/gene counts are out of scope for that path
-- so those columns are simply absent (unlike the v3/v4/v5 tables).
--
-- Applied via recipes/enrich_transfer/transfer.py --fast, never written to by
-- hand.

CREATE TABLE IF NOT EXISTS enriched_studies_fast (
    accession TEXT PRIMARY KEY,
    title TEXT,
    n_samples INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS enriched_samples_fast (
    study_accession TEXT NOT NULL,
    sample TEXT NOT NULL,
    age TEXT,
    sex TEXT,
    ethnicity TEXT,
    phenotype TEXT,
    cell_type TEXT,
    tissue TEXT,
    strain TEXT,
    disease TEXT,
    assay TEXT,
    assay_category TEXT,
    cell_line TEXT,
    treatment TEXT,
    development_stage TEXT,
    sample_type TEXT,
    genetic_modification TEXT,
    PRIMARY KEY (study_accession, sample)
);

